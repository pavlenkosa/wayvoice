_TRANSLATIONS = {"ru": _RU, "en": _EN}


def resolve_language(value: str | None) -> str:
    value = (value or "auto").strip().lower()
    if value in {"ru", "en"}:
        return value
    try:
        lang, _encoding = locale.getlocale()
    except Exception:
        lang = None
    if not lang:
        try:
            lang = locale.getdefaultlocale()[0]  # type: ignore[attr-defined]
        except Exception:
            lang = None
    return "ru" if str(lang or "").lower().startswith("ru") else "en"


def tr(key: str, language: str | None = None, **kwargs: Any) -> str:
    lang = resolve_language(language)
    value = _TRANSLATIONS.get(lang, _EN).get(key, _EN.get(key, key))
    if kwargs:
        try:
            return value.format(**kwargs)
        except Exception:
            return value
    return value
